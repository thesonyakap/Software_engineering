# Импортируем модуль datetime, чтобы измерить время выполнения программы
from datetime import datetime
# Импортируем функцию sqrt из модуля math для вычисления квадратного корня
from math import sqrt

# Определяем функцию main, которая принимает неограниченное количество именованных аргументов (**kwargs)
def main(**kwargs):
    # Перебираем все пары ключ-значение в переданных аргументах
    for key in kwargs.items():
        # Вычисляем результат по формуле: sqrt(x^2 + y^2)
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)
        # Выводим полученное значение в консоль
        print(result)

# Проверяем, что файл запущен напрямую (а не импортирован)
if __name__ == '__main__':
    # Сохраняем текущее время перед запуском программы
    start_time = datetime.now()
    # Вызываем функцию main с несколькими наборами координат
    main(
        one=[10, 3],
        two=[5, 4],
        three=[15, 13],
        four=[93, 53],
        five=[133, 15]
    )
    # Вычисляем разницу между текущим временем и стартом — время выполнения
    time_costs = datetime.now() - start_time
    # Выводим время выполнения программы
    print(f"Время выполнения программы - {time_costs}")
